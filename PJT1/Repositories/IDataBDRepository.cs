using System.Collections.Generic;  // Для IEnumerable
using PJT1.Models;                // Для DataBD

namespace PJT1.Repositories
{
    /// <summary>
    /// ИНТЕРФЕЙС РЕПОЗИТОРИЯ IDataBDRepository
    /// 
    /// Что такое интерфейс?
    /// Интерфейс - это контракт (договор) между классами.
    /// Он определяет, какие методы должен иметь класс,
    /// но НЕ реализует их.
    /// 
    /// Зачем нужны интерфейсы?
    /// 1. Абстракция - скрываем детали реализации
    /// 2. Полиморфизм - один интерфейс, много реализаций
    /// 3. Тестирование - легко подменить реализацию на тестовую
    /// 4. Гибкость - можно легко заменить способ хранения данных
    /// 
    /// Преимущества:
    /// - Код, использующий репозиторий, не знает, где хранятся данные
    /// - Можно заменить List на базу данных без изменения кода
    /// - Легче тестировать
    /// </summary>
    public interface IDataBDRepository
    {
        // ============================================================
        // МЕТОДЫ ДЛЯ РАБОТЫ С ДАННЫМИ (CRUD)
        // ============================================================

        /// <summary>
        /// ПОЛУЧИТЬ ВСЕ ЗАПИСИ
        /// 
        /// IEnumerable<DataBD> - интерфейс для перебора коллекции
        /// Возвращает все записи из репозитория
        /// </summary>
        /// <returns>Коллекция всех записей</returns>
        IEnumerable<DataBD> GetAll();

        /// <summary>
        /// ПОЛУЧИТЬ ЗАПИСЬ ПО ID
        /// 
        /// DataBD? - nullable тип (может быть null)
        /// Возвращает объект или null, если не найден
        /// </summary>
        /// <param name="id">Уникальный идентификатор</param>
        /// <returns>Объект DataBD или null</returns>
        DataBD GetById(int id);

        /// <summary>
        /// ДОБАВИТЬ ЗАПИСЬ
        /// 
        /// void - метод ничего не возвращает
        /// Принимает объект DataBD для добавления
        /// </summary>
        /// <param name="data">Объект DataBD</param>
        void Add(DataBD data);

        /// <summary>
        /// ДОБАВИТЬ НЕСКОЛЬКО ЗАПИСЕЙ
        /// 
        /// Используется для массового импорта из Excel
        /// </summary>
        /// <param name="dataList">Коллекция объектов DataBD</param>
        void AddRange(IEnumerable<DataBD> dataList);

        /// <summary>
        /// УДАЛИТЬ ЗАПИСЬ ПО ID
        /// 
        /// Находит запись по идентификатору и удаляет
        /// </summary>
        /// <param name="id">Идентификатор записи</param>
        void Delete(int id);

        /// <summary>
        /// ОЧИСТИТЬ ВСЕ ЗАПИСИ
        /// 
        /// Удаляет все данные из репозитория
        /// </summary>
        void Clear();

        /// <summary>
        /// ПОЛУЧИТЬ КОЛИЧЕСТВО ЗАПИСЕЙ
        /// </summary>
        /// <returns>Количество записей</returns>
        int Count();

        // ============================================================
        // МЕТОДЫ ДЛЯ РАБОТЫ С ВНЕШНИМИ ИСТОЧНИКАМИ
        // ============================================================

        /// <summary>
        /// ИМПОРТ ИЗ EXCEL
        /// 
        /// Читает данные из Excel файла и добавляет в репозиторий
        /// Читает только первые два поля: Tagname и Loop
        /// </summary>
        /// <param name="filePath">Путь к Excel файлу</param>
        void ImportFromExcel(string filePath);
    }
}