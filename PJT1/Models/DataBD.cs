// ================================================================
using System;  // Для работы с DateTime

namespace PJT1.Models
{
    /// <summary>
    /// КЛАСС DataBD - Модель данных
    /// 
    /// Представляет одну запись с информацией из Excel.
    /// Каждый объект этого класса хранит данные одной строки.
    /// 
    /// Класс - это шаблон для создания объектов.
    /// Объект - конкретный экземпляр класса.
    /// 
    /// Пример: Класс - это чертеж автомобиля.
    /// Объект - это конкретный автомобиль, собранный по чертежу.
    /// </summary>
    public class DataBD
    {
        // ============================================================
        // СВОЙСТВА КЛАССА
        // ============================================================
        // Свойства - это специальные методы, которые позволяют
        // безопасно получать и устанавливать значения полей.
        // 
        // Синтаксис: public Тип Имя { get; set; }
        // get - возвращает значение
        // set - устанавливает значение
        // ============================================================

        /// <summary>
        /// Уникальный идентификатор записи
        /// int - целочисленный тип (от -2 млрд до +2 млрд)
        /// Автоматически присваивается при добавлении в репозиторий
        /// </summary>
        public int Id { get; set; }

        /// <summary>
        /// Имя тега (первое поле из Excel)
        /// string - строковый тип для хранения текста
        /// </summary>
        public string Tagname { get; set; }

        /// <summary>
        /// Цикл/контур (второе поле из Excel)
        /// string - строковый тип
        /// </summary>
        public string Loop { get; set; }

        /// <summary>
        /// Комментарий (третье поле из Excel)
        /// string - строковый тип
        /// </summary>
        public string Comment { get; set; }

        /// <summary>
        /// Дата и время создания записи
        /// DateTime - специальный тип для хранения даты и времени
        /// Автоматически устанавливается при создании объекта
        /// </summary>
        public DateTime CreatedDate { get; set; }

        // ============================================================
        // КОНСТРУКТОРЫ КЛАССА
        // ============================================================
        // Конструктор - специальный метод, который вызывается
        // при создании объекта (при использовании new).
        // 
        // Виды конструкторов:
        // 1. По умолчанию (без параметров) - создает пустой объект
        // 2. С параметрами - создает объект с заполненными данными
        // ============================================================

        /// <summary>
        /// КОНСТРУКТОР ПО УМОЛЧАНИЮ
        /// 
        /// Вызывается при: new DataBD()
        /// Используется, когда нужно создать пустой объект
        /// 
        /// Особенности:
        /// - Все строковые поля инициализируются пустыми строками
        /// - CreatedDate получает текущую дату и время
        /// - Id будет присвоен при добавлении в репозиторий
        /// </summary>
        public DataBD()
        {
            // string.Empty - это пустая строка ""
            // Используем вместо null, чтобы избежать ошибок
            Tagname = string.Empty;
            Loop = string.Empty;
            Comment = string.Empty;

            // DateTime.Now - возвращает текущую дату и время
            CreatedDate = DateTime.Now;
        }

        /// <summary>
        /// КОНСТРУКТОР ДЛЯ ИМПОРТА ИЗ EXCEL
        /// 
        /// Вызывается при: new DataBD("Motor1", "LoopA")
        /// Используется при импорте первых двух полей из Excel
        /// 
        /// this() - вызывает конструктор по умолчанию
        /// this означает "текущий объект"
        /// 
        /// ?? - оператор объединения с null
        /// Если значение слева null - берется значение справа
        /// </summary>
        /// <param name="tagname">Имя тега (первое поле Excel)</param>
        /// <param name="loop">Цикл (второе поле Excel)</param>
        public DataBD(string tagname, string loop) : this()
        {
            // Проверяем, что переданные значения не null
            Tagname = tagname ?? string.Empty;
            Loop = loop ?? string.Empty;
            // Comment остается пустым (уже установлен в базовом конструкторе)
        }

        /// <summary>
        /// КОНСТРУКТОР ДЛЯ РУЧНОГО ДОБАВЛЕНИЯ
        /// 
        /// Вызывается при: new DataBD("Motor1", "LoopA", "Двигатель 1")
        /// Используется при ручном добавлении записи через форму
        /// 
        /// Перегрузка конструкторов:
        /// Это когда у класса есть несколько конструкторов
        /// с разным количеством или типами параметров
        /// </summary>
        /// <param name="tagname">Имя тега</param>
        /// <param name="loop">Цикл</param>
        /// <param name="comment">Комментарий</param>
        public DataBD(string tagname, string loop, string comment) : this()
        {
            // Заполняем все три поля
            Tagname = tagname ?? string.Empty;
            Loop = loop ?? string.Empty;
            Comment = comment ?? string.Empty;
        }

        // ============================================================
        // ПЕРЕОПРЕДЕЛЕНИЕ МЕТОДА ToString()
        // ============================================================
        // ToString() - это метод, который есть у всех объектов в C#
        // Он возвращает строковое представление объекта
        // 
        // override - ключевое слово для переопределения методов
        // базового класса (object)
        // 
        // Зачем переопределять?
        // По умолчанию возвращает имя класса: "PJT1.Models.DataBD"
        // Мы хотим видеть содержание объекта, а не его тип
        // ============================================================

        /// <summary>
        /// Возвращает строковое представление объекта DataBD
        /// Используется при выводе в консоль и в списках
        /// </summary>
        /// <returns>Строка с информацией об объекте</returns>
        public override string ToString()
        {
            // Интерполяция строк ($" ... {переменная} ... ")
            // Позволяет вставлять значения переменных прямо в строку
            return $"{Tagname} - {Loop} - {Comment}";
        }
    }
}